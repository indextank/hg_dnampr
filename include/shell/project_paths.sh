# env_loader.sh::_normalize_project_relative_env_paths 统一规范化为绝对路径，
# 供 shell 侧检查/生成文件使用；Compose 仍按 env_file 的相对路径解析。
# 新增需规范化的路径变量只在此处追加一项。
